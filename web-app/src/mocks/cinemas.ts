export function findCinemaByShowtimeId(showtimeId: string): {
  cinema: CinemaWithShowtimes
  showtime: ShowtimeItem
  movie?: {
    id: string
    title: string
    posterUrl: string
  }
} | undefined {
  for (const cinema of MOCK_CINEMAS) {
    // 1. Kiểm tra danh sách showtimes trực tiếp của rạp (backward compatibility)
    const showtime = cinema.showtimes.find((s) => s.id === showtimeId)
    if (showtime) {
      return { cinema, showtime }
    }

    // 2. Kiểm tra danh sách lịch chiếu theo từng phim (movieSchedules)
    if (cinema.movieSchedules) {
      for (const schedule of cinema.movieSchedules) {
        const st = schedule.showtimes.find((s) => s.id === showtimeId)
        if (st) {
          return {
            cinema,
            showtime: st,
            movie: {
              id: schedule.movieId,
              title: schedule.movieTitle,
              posterUrl: schedule.posterUrl,
            },
          }
        }
      }
    }
  }
  return undefined
}
